function demoSourceDigest(messageId: string) {
  let hash = 2166136261;
  for (const character of messageId) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0).toString(16).padStart(8, '0').repeat(8);
}

function withDemoTranslation(message: Message): Message {
  if (!message.translatedText || !message.targetLanguage || message.translation) return message;
  const fixtureTimestamp = '2026-08-04T12:00:00.000Z';
  return {
    ...message,
    languageDetection: message.languageDetection ?? {
      state: 'completed',
      detectedLanguage: message.sourceLanguage,
      confidence: 1,
      method: 'synthetic-demo-fixture',
      detectedAt: fixtureTimestamp,
    },
    translation: {
      id: `translation-${message.id}`,
      sourceLanguage: message.sourceLanguage,
      targetLanguage: message.targetLanguage,
      sourceBodySha256: demoSourceDigest(message.id),
      status: 'completed',
      translatedText: message.translatedText,
      provider: 'synthetic-demo',
      model: 'fixture-v1',
      confidence: 1,
      policyVersion: 1,
      policyState: 'current',
      reviewedByUserId: null,
      reviewedAt: null,
      failureCode: null,
      createdAt: fixtureTimestamp,
      updatedAt: fixtureTimestamp,
      correction: null,
    },
  };
}

